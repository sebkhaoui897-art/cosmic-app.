import time

def cosmic_guide():
    print("=" * 45)
    print("       🌌 مرشد أسرار الكون (Cosmic Guide) 🌌       ")
    print("=" * 45)
    print("أهلاً بك في رحلة التأمل في ملكوت السماوات والأرض...\n")
    time.sleep(1)
    
    score = 0
    
    while True:
        print("-" * 45)
        print("اختر المحطة التي تريدها:")
        print("1. 🌠 استكشاف المحطات الكونية")
        print("2. 📖 آيات للتفكر والتدبر")
        print("3. 🧠 اختبار معلوماتك الكونية (سؤال وجواب)")
        print("4. 🚪 خروج من التطبيق")
        
        choice = input("\nأدخل رقم اختيارك (1-4): ")
        
        if choice == '1':
            print("\n--- المحطات الكونية ---")
            print("1. الانفجار العظيم وتوسع الكون")
            print("2. الثقوب السوداء والجاذبية")
            print("3. مواقع النجوم والضوء القديم")
            sub_choice = input("اختر رقم الظاهرة للتفصيل (1-3): ")
            
            if sub_choice == '1':
                print("\n[التفسير]: الكون يتوسع باستمرار.")
                print("قال الله تعالى: (والسماء بنيناها بأيدي وإنا لموسعون).\n")
            elif sub_choice == '2':
                print("\n[التفسير]: الثقوب السوداء ذات جاذبية لا يهرب منها الضوء.")
                print("قال الله تعالى: (فلا أقسم بمواقع النجوم وإنه لقسم لو تعلمون عظيم).\n")
            elif sub_choice == '3':
                print("\n[التفسير]: ما نراه من النجوم ربما انطفأ منذ ملايين السنين ووصلنا ضوؤه فقط.\n")
                
        elif choice == '2':
            print("\n--- 📖 آيات للتفكر والتدبر ---")
            print("1. آية في خلق السماوات والأرض")
            print("2. آية في تسخير الشمس والقمر")
            verse_choice = input("اختر رقم الاختيار (1-2): ")
            
            if verse_choice == '1':
                print("\nقال تعالى: (إِنَّ فِي خَلْقِ السَّمَاوَاتِ وَالْأَرْضِ وَاخْتِلَافِ اللَّيْلِ وَالنَّهَارِ لَآيَاتٍ لِّأُولِي الْأَلْبَابِ)")
                print("💡 التفكر في عظمة الخلق يورث الحكمة وطمأنينة القلب.\n")
            elif verse_choice == '2':
                print("\nقال تعالى: (وَسَخَّرَ لَكُمُ الشَّمْسَ وَالْقَمَرَ دَائِبَيْنِ ۖ وَسَخَّرَ لَكُمُ اللَّيْلَ وَالنَّهَارَ)")
                print("💡 انضباط حركة الأجرام الكونية دليل على دقة وبديع صنع الخالق سبحانه.\n")
                
        elif choice == '3':
            print("\n" + "="*5)
            print("【 اختبار معلومات الفضاء 】")
            print("سؤال: هل الكون ساكن لا يتغير أم أنه في حالة توسع مستمر؟")
            print("1. ساكن وثابت")
            print("2. يتوسع باستمرار")
            
            ans = input("أدخل رقم الإجابة الصحيحة (1 أو 2): ")
            if ans == '2':
                print("✨ إجابة صحيحة! أحسنت، الكون يتوسع كما أخبرنا القرآن والعلم.\n")
                score += 1
            else:
                print("❌ إجابة غير دقيقة، العلم الحديث أثبت أن الكون يتوسع (وإنا لموسعون).\n")
                
            print(f"نقاطك الحالية في الاختبار: {score}\n")
            
        elif choice == '4':
            print(f"\n✨ شكراً لرحلتك معنا. مجموع نقاطك النهائية: {score}. استمر في التأمل والتعلم يا عبد المنعم! 🚀")
            break
        else:
            print("\n❌ اختيار غير صحيح، يرجى إدخال رقم بين 1 و 4.\n")
        
        time.sleep(1)

# تشغيل التطبيق
cosmic_guide()
